function readStoredLocale() {
  try {
    if (typeof localStorage === 'undefined' || !localStorage || typeof localStorage.getItem !== 'function') return 'zh';
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'zh') return stored;
  } catch (_e) { /* ignore */ }
  return 'zh';
}

let locale = readStoredLocale();

export function getLocale() {
  return locale;
}

export function intlLocale() {
  return locale === 'en' ? 'en-US' : 'zh-CN';
}

export function t(key, vars) {
  const table = locale === 'en' ? en : zh;
  let msg = table[key];
  if (msg == null) msg = zh[key];
  if (msg == null) return key;
  if (typeof msg === 'function') return msg(vars || {});
  if (!vars) return msg;
  return fill(msg, vars);
}

function applyDocumentLocale() {
  try {
    if (typeof document === 'undefined' || !document || !document.documentElement) return;
    document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN';
    const title = t('app.title');
    if (title) document.title = title;
    if (typeof document.querySelector === 'function') {
      const meta = document.querySelector('meta[name="description"]');
      if (meta && typeof meta.setAttribute === 'function') meta.setAttribute('content', t('app.description'));
    }
  } catch (_e) { /* ignore */ }
}

export function setLocale(next) {
  if (next !== 'zh' && next !== 'en') return;
  if (next === locale) return;
  locale = next;
  try {
    if (typeof localStorage !== 'undefined' && localStorage && typeof localStorage.setItem === 'function') {
      localStorage.setItem(STORAGE_KEY, next);
    }
  } catch (_e) { /* ignore */ }
  applyDocumentLocale();
  try {
    if (typeof location !== 'undefined' && location && typeof location.reload === 'function') location.reload();
  } catch (_e) { /* ignore */ }
}

applyDocumentLocale();

if (typeof window !== 'undefined') {
  window.IceI18n = { t, getLocale, setLocale, intlLocale };
}
